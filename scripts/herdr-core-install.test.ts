test("probe reports facts only and changes nothing", () => {
  const f = fixture();
  writeFileSync(join(f.fakeBin, "herdr"), "#!/bin/sh\n", { mode: 0o755 });
  const result = f.run("herdr_core_probe");
  expect(result.code).toBe(0);
  const facts = Object.fromEntries(
    result.out
      .trim()
      .split("\n")
      .map((line) => line.split(/=(.*)/s).slice(0, 2)),
  );
  expect(facts.core).toBe("");
  expect(facts.herdr).toBe(join(f.fakeBin, "herdr"));
  expect(facts.dir).toBe(f.bin);
  expect(facts.target).toMatch(/^(linux|macos)-(x86_64|aarch64)$/);
  expect(result.log).not.toContain("curl");
  expect(existsSync(f.bin)).toBe(false);
});
