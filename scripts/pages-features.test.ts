import { afterEach, expect, test } from "bun:test";
import { mkdtempSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import {
  readFeatureReference,
  renderFeatures,
  renderFeatureSite,
} from "./pages-features";

const roots: string[] = [];
afterEach(() => {
  for (const root of roots.splice(0))
    rmSync(root, { recursive: true, force: true });
});

test("the public reference contains contracts and usage, with repository links rebased", () => {
  const root = mkdtempSync(join(tmpdir(), "pages-features-"));
  roots.push(root);
  const write = (path: string, text: string) => {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  };
  write(
    "openspec/specs/example/spec.md",
    "## Purpose\n\nSee [guide](../../../docs/guide.md).\n\n## Requirements\n\n### Requirement: Example behavior\n",
  );
  write(
    "openspec/specs/example/notes.md",
    "**Code:**\n\n- `server/src/example.ts`\n\n## Usage reference\n\nChoose [settings](../../../docs/settings.md#example).\n",
  );
  const output = renderFeatures(readFeatureReference(root));
  expect(output).toContain("Generated by bun run build:site");
  expect(output).toContain("[guide](docs/guide.md)");
  expect(output).toContain("[Contract](openspec/specs/example/spec.md)");
  expect(output).toContain("[Notes](openspec/specs/example/notes.md)");
  expect(output).toContain(
    "[Example behavior](openspec/specs/example/spec.md#requirement-example-behavior)",
  );
  expect(output).toContain("Choose [settings](docs/settings.md#example).");
  expect(output).not.toContain("**Code:**");
  expect(output).not.toContain("server/src/example.ts");
});

test("the site can render a new capability's usage before its delta is archived", () => {
  const root = mkdtempSync(join(tmpdir(), "pages-features-"));
  roots.push(root);
  mkdirSync(join(root, "openspec/specs/example"), { recursive: true });
  mkdirSync(join(root, "openspec/changes/new/specs/example"), {
    recursive: true,
  });
  writeFileSync(
    join(root, "openspec/specs/example/notes.md"),
    "## Usage reference\n\nNew usage.\n",
  );
  const specPath = "openspec/changes/new/specs/example/spec.md";
  writeFileSync(
    join(root, specPath),
    "## ADDED Requirements\n\n### Requirement: New behavior\n",
  );
  const output = renderFeatures(readFeatureReference(root));
  expect(output).toContain(`[Contract](${specPath})`);
  expect(output).toContain("New behavior");
  expect(output).toContain("New usage.");
  rmSync(join(root, specPath));
  expect(() => readFeatureReference(root)).toThrow(
    "notes need a current spec or active change delta",
  );
});

test("site links preserve local anchors and link contracts to their repository source", () => {
  const html = renderFeatureSite(
    "## Runtime support\n\n[contract](openspec/specs/example/spec.md#requirement-example) [here](#runtime-support)\n",
  );
  expect(html).toContain('id="runtime-support"');
  expect(html).toContain(
    'href="https://github.com/IvoryHeart/herdr-world/blob/main/openspec/specs/example/spec.md#requirement-example"',
  );
  expect(html).toContain('href="#runtime-support"');
});
