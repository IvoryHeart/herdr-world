import { existsSync, readFileSync } from "node:fs";
import { posix } from "node:path";

export type Capability = {
  id: string;
  specPath: string;
  notesPath: string;
  purpose: string;
  requirements: string[];
  notes: string;
  codePaths: string[];
};

export function readCapabilities(root = process.cwd()): Capability[] {
  const dirs = new Set(
    [
      ...new Bun.Glob("openspec/specs/**/{spec,notes}.md").scanSync({
        cwd: root,
      }),
    ].map((p) => posix.dirname(p)),
  );
  return [...dirs].sort().map((dir) => {
    const id = dir.slice("openspec/specs/".length);
    const specPath = existsSync(`${root}/${dir}/spec.md`)
      ? `${dir}/spec.md`
      : [
          ...new Bun.Glob(`openspec/changes/*/specs/${id}/spec.md`).scanSync({
            cwd: root,
          }),
        ].sort()[0];
    if (!specPath)
      throw new Error(
        `${dir}: notes need a current spec or active change delta`,
      );
    const spec = readFileSync(`${root}/${specPath}`, "utf8");
    const notesPath = `${dir}/notes.md`;
    const notes = existsSync(`${root}/${notesPath}`)
      ? readFileSync(`${root}/${notesPath}`, "utf8")
      : "";
    const code =
      /(?:\*\*Code(?: paths)?:\*\*|## Code paths)\s*\n([\s\S]*?)(?=\n(?:\*\*[^\n]+:\*\*|## )|$)/.exec(
        notes,
      )?.[1] ?? "";
    return {
      id,
      specPath,
      notesPath,
      notes,
      purpose:
        /## Purpose\s*\n([\s\S]*?)(?=\n## |$)/.exec(spec)?.[1].trim() ?? "",
      requirements: [...spec.matchAll(/^### Requirement: (.+)$/gm)].map(
        (m) => m[1],
      ),
      codePaths: [...code.matchAll(/^- `([^`]+)`/gm)].map((m) => m[1]),
    };
  });
}

const words = (text: string) =>
  text.toLowerCase().match(/[\p{L}\p{N}]+/gu) ?? [];
const contains = (text: string, term: string) =>
  words(text).some((word) => word.startsWith(term));

export function findCapabilities(
  caps: Capability[],
  query: string,
): Capability[] {
  const terms = words(query);
  if (!terms.length) return caps;
  return (
    caps
      .filter((c) =>
        terms.every((t) =>
          contains([c.id, c.purpose, ...c.requirements, c.notes].join(" "), t),
        ),
      )
      // Prefer the focused capability over large shared references.
      .sort(
        (a, b) => a.notes.length - b.notes.length || a.id.localeCompare(b.id),
      )
  );
}

/** Rebase repository links when collecting notes into the generated root file. */
export function rootLinks(text: string, source: string): string {
  return text.replace(
    /(\]\()([^\s)]+)(\))/g,
    (all, before, href: string, after) => {
      if (/^(?:[a-z][a-z\d+.-]*:|\/\/)/i.test(href)) return all;
      const [path, fragment] = href.split("#", 2);
      const target = path
        ? posix.normalize(posix.join(posix.dirname(source), path))
        : source;
      return `${before}${target === "FEATURES.md" ? "" : target}${fragment === undefined ? "" : `#${fragment}`}${after}`;
    },
  );
}

export function renderFeatures(caps: Capability[]): string {
  return (
    "<!-- Generated by bun run build:site from OpenSpec specs and notes. Do not edit or commit. -->\n\n# Herdr World features\n\n" +
    caps
      .map((c) =>
        [
          `## ${c.id}`,
          "",
          rootLinks(c.purpose, c.specPath),
          "",
          `[Contract](${c.specPath}) · [Notes](${c.notesPath})`,
          "",
          ...c.requirements.map(
            (name) =>
              `- [${name}](${c.specPath}#requirement-${name
                .toLowerCase()
                .replace(/[^\p{L}\p{N}_\-\s]/gu, "")
                .replace(/\s/g, "-")})`,
          ),
          "",
          rootLinks(
            c.notes.split("## Usage reference\n")[1] ?? "",
            c.notesPath,
          ),
          "",
        ].join("\n"),
      )
      .join("\n")
  );
}

/** Publish the generated reference alongside the tutorial, with repository source links. */
export function renderFeatureSite(markdown: string): string {
  const ids = new Map<string, number>();
  const html = Bun.markdown
    .html(markdown)
    .replace(/<h([1-6])>(.*?)<\/h\1>/g, (_, level, title: string) => {
      const slug = title
        .replace(/<[^>]*>/g, "")
        .toLowerCase()
        .replace(/[^\p{L}\p{N}_\-\s]/gu, "")
        .replace(/\s/g, "-");
      const count = ids.get(slug) ?? 0;
      ids.set(slug, count + 1);
      return `<h${level} id="${slug}${count ? `-${count}` : ""}">${title}</h${level}>`;
    })
    .replace(/(href|src)="([^"]+)"/g, (all, attr, href: string) =>
      /^(?:[a-z][a-z\d+.-]*:|\/\/|#)/i.test(href)
        ? all
        : `${attr}="https://github.com/IvoryHeart/herdr-world/${attr === "src" ? "raw" : "blob"}/main/${href}"`,
    );
  return `<!doctype html><html lang="en"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Herdr World features</title><link rel="stylesheet" href="../styles.css"><link rel="stylesheet" href="../tutorial.css"><body class="tutorial-page"><main class="shell"><nav><a href="../">Home</a> · <a href="../tutorial/">Tutorial</a> · <a href="../help/">Help</a> · <a href="../FEATURES.md">Download Markdown</a></nav><article class="tutorial-content">${html}</article></main></body></html>`;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const query = args
    .filter((a) => a !== "--json")
    .join(" ")
    .trim();
  if (!query) {
    console.error('Usage: bun run where "<words>" [--json]');
    process.exitCode = 2;
  } else {
    const matches = findCapabilities(readCapabilities(), query);
    console.log(
      args.includes("--json")
        ? JSON.stringify(
            matches,
            (key, value) => (key === "notes" ? undefined : value),
            2,
          )
        : matches
            .map(
              (c) =>
                `${c.id}\n  Spec: ${c.specPath}\n  Notes: ${c.notesPath}\n  Code: ${c.codePaths.join(", ")}\n  Requirements: ${c.requirements
                  .filter((r) => words(query).some((t) => contains(r, t)))
                  .slice(0, 3)
                  .join("; ")}`,
            )
            .join("\n\n") || `No capabilities match: ${query}`,
    );
  }
}
