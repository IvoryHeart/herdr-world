import { join, resolve } from "node:path";

/** Static imports work in Bun, compiled binaries, Vite and browser bundles. */
export async function features(root: string, check = false) {
  for (const [directory, entry] of [
    ["server/src/features", "register.ts"],
    ["web/src/features", "mount.tsx"],
  ]) {
    const paths = [
      ...new Bun.Glob(`**/${entry}`).scanSync({
        cwd: join(root, directory),
        onlyFiles: true,
      }),
    ]
      .map((path) => path.replaceAll("\\", "/"))
      .sort();
    const names = new Set<string>();
    const lines = paths.map((path) => {
      const name = `feature_${path.slice(0, -(entry.length + 1)).replace(/[^a-zA-Z0-9]/g, "_")}`;
      if (names.has(name)) throw new Error(`Duplicate feature export: ${name}`);
      names.add(name);
      return `export * as ${name} from ${JSON.stringify("./" + path.replace(/\.tsx?$/, ""))};`;
    });
    const expected = [
      "// Generated by features:generate. Do not edit.",
      ...lines,
    ];
    if (!lines.length) expected.push("export {};");
    const file = Bun.file(join(root, directory, "index.gen.ts"));
    if (check) {
      const actual = (await file.exists())
        ? (await file.text()).split(/\r?\n/).filter(Boolean)
        : [];
      if (
        actual.length !== expected.length ||
        expected.some((line) => !actual.includes(line))
      )
        throw new Error(
          `${directory}/index.gen.ts is stale; run bun run features:generate`,
        );
    } else await Bun.write(file, expected.join("\n") + "\n");
  }
}

if (import.meta.main) {
  const check = process.argv.includes("--check");
  await features(resolve(import.meta.dir, ".."), check);
  console.info(check ? "Feature indexes checked" : "Feature indexes generated");
}
