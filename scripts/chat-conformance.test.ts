import { expect, test } from "bun:test";
import type { ConversationMessage } from "../server/src/agent/conversation";
import { conformance } from "./chat-conformance";

const message = (
  role: "user" | "assistant",
  text: string,
  second: number,
): ConversationMessage => ({
  id: `${role}-${second}`,
  role,
  kind: "message",
  text,
  sent_at: new Date(Date.UTC(2026, 9, 22, 9, 0, second)).toISOString(),
});

test("a plain exchange passes", () => {
  expect(
    conformance([message("user", "Hi", 1), message("assistant", "Hello", 2)]),
  ).toEqual({ failures: [], notes: [] });
});

test("injected context shown as the user's words fails", () => {
  for (const text of [
    "# AGENTS.md instructions for /work/demo",
    "<environment_context>",
    "<task-notification>",
    "Caveat: The messages below were generated by the user",
    "This session is being continued from a previous conversation",
  ])
    expect(
      conformance([message("user", text, 1), message("assistant", "Ok", 2)])
        .failures,
    ).toEqual(["injected_user_text"]);
});

test("transcript states that are not reader bugs are notes", () => {
  expect(conformance([message("user", "Hi", 1)]).notes).toEqual([
    "no_exchange",
  ]);
  expect(
    conformance([message("assistant", "Late", 2), message("user", "Early", 1)])
      .notes,
  ).toEqual(["timestamps_out_of_order"]);
});
