/**
 * The help page, generated from the help declarations (web/src/help/):
 * docs/HELP.md for GitHub, and the site's /help/ page (scripts/build-pages.ts)
 * rendered from the same Markdown. Nobody edits docs/HELP.md by hand:
 *
 *   bun run help:docs      writes docs/HELP.md
 *   bun run help:check     fails when it is out of date
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { firstRunPath } from "../web/src/help/entries";
import {
  compareVersions,
  HELP_PLACE_LABELS,
  HELP_PLACES,
  type HelpEntry,
  helpPictureFile,
  helpPictureSizes,
} from "../web/src/help/helpEntry";
import {
  HELP_DOC,
  HELP_PICTURE_CROPS,
  helpEntries,
  ROOT,
} from "./help-declarations";

const GENERATED =
  "<!-- Generated by `bun run help:docs` from the help declarations (web/src/**/*.help.ts). Do not edit by hand. -->";

/** An entry's anchor on the page: its id with the dot as a hyphen. */
export function helpAnchorId(entry: Pick<HelpEntry, "id">) {
  return entry.id.replace(".", "-");
}

/** The picture the page shows: desktop when captured there, in light. */
function pagePicture(entry: HelpEntry) {
  const sizes = helpPictureSizes(entry);
  const size = sizes.includes("desktop") ? "desktop" : sizes[0]!;
  return `../web/public/help/${helpPictureFile(entry, size, "light")}`;
}

function entrySection(entry: HelpEntry) {
  return [
    `<a id="${helpAnchorId(entry)}"></a>`,
    "",
    `### ${entry.title}`,
    "",
    `![${entry.title}](${pagePicture(entry)})`,
    "",
    entry.summary,
    "",
    ...entry.steps.map((step, index) => `${index + 1}. ${step}`),
    "",
    `Where: ${entry.where}. Since ${entry.since}.`,
    "",
  ];
}

/** docs/HELP.md: the first-run path, what is new, then each place's help. */
export function renderHelpDoc(entries: readonly HelpEntry[] = helpEntries()) {
  const newest = entries
    .map((entry) => entry.since)
    .sort(compareVersions)
    .at(-1);
  const recent = entries.filter((entry) => entry.since === newest);
  const lines = [
    GENERATED,
    "",
    "# What you can do in Herdr World",
    "",
    "Every World screen answers this too: press ? beside the views (on a phone, the views button), then **What can I do here?** Each entry there has a Try button that shows you the control.",
    "",
    "## Start here",
    "",
    ...firstRunPath(entries).map(
      (entry, index) =>
        `${index + 1}. [${entry.title}](#${helpAnchorId(entry)}): ${entry.summary}`,
    ),
    "",
  ];
  if (newest)
    lines.push(
      `## New in ${newest}`,
      "",
      ...recent.map((entry) => `- [${entry.title}](#${helpAnchorId(entry)})`),
      "",
    );
  for (const place of HELP_PLACES) {
    const here = entries.filter((entry) => entry.place === place);
    if (!here.length) continue;
    lines.push(`## ${HELP_PLACE_LABELS[place]}`, "");
    for (const entry of here) lines.push(...entrySection(entry));
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

export type HelpSitePage = {
  content: string;
  navigation: string;
  /** Pictures the page shows, by file name under web/public/help/. */
  pictures: string[];
};

const PICTURE =
  /^\.\.\/web\/public\/help\/([^/]+\.(desktop|phone)\.(light|dark)\.webp)$/;

/**
 * The site's /help/ page from docs/HELP.md (trusted repository Markdown):
 * section ids for the contents, pictures under ../assets/help/ with their
 * size reserved.
 */
export async function renderHelpSite(markdown: string): Promise<HelpSitePage> {
  const navigation: string[] = [];
  const html = Bun.markdown
    .html(markdown.replace(/^<!--.*-->\n/, ""))
    .replace(/<h([12])>(.*?)<\/h\1>/g, (_, level: string, title: string) => {
      if (level === "1") return `<h1 id="help-title">${title}</h1>`;
      const id = `help-${title
        .toLowerCase()
        .replace(/[^a-z0-9]+/g, "-")
        .replace(/^-|-$/g, "")}`;
      navigation.push(`<li><a href="#${id}">${title}</a></li>`);
      return `<h2 id="${id}">${title}</h2>`;
    });
  const pictures: string[] = [];
  const content = await new HTMLRewriter()
    .on("img", {
      element(element) {
        const match = PICTURE.exec(element.getAttribute("src") ?? "");
        if (!match)
          throw new Error("Help page pictures come from web/public/help/");
        const [, file, size] = match as unknown as [
          string,
          string,
          "desktop" | "phone",
        ];
        pictures.push(file);
        element.setAttribute("src", `../assets/help/${file}`);
        element.setAttribute("width", String(HELP_PICTURE_CROPS[size].width));
        element.setAttribute("height", String(HELP_PICTURE_CROPS[size].height));
        element.setAttribute("loading", "lazy");
        element.setAttribute("decoding", "async");
      },
    })
    .transform(new Response(html))
    .text();
  return { content, navigation: `<ol>${navigation.join("")}</ol>`, pictures };
}

/** Whether docs/HELP.md matches the declarations. */
export function helpDocCurrent(root = ROOT, entries = helpEntries()) {
  try {
    return (
      readFileSync(join(root, HELP_DOC), "utf8") === renderHelpDoc(entries)
    );
  } catch {
    return false;
  }
}

if (import.meta.main) {
  if (process.argv.includes("--write")) {
    writeFileSync(join(ROOT, HELP_DOC), renderHelpDoc());
    process.stdout.write(`help docs: wrote ${HELP_DOC}\n`);
  } else if (!helpDocCurrent()) {
    process.stderr.write(`${HELP_DOC} is out of date; run bun run help:docs\n`);
    process.exitCode = 1;
  }
}
