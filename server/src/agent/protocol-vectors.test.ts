test.each([
  ["claude", "claude-composer-empty.txt", "claude-composer-multiline.txt"],
  ["codex", "codex-question.txt", "codex-question-notes.txt"],
] as const)(
  "%s recorded payload rewrites invalidate a constant-metadata local transcript",
  async (agent, before, after) => {
    // Real sanitized screen captures (versions/provenance in the adjacent README)
    // inside synthetic native transcript envelopes. No private transcript needed.
    const screens = await Promise.all(
      [before, after].map((name) =>
        readFile(
          new URL(`./fixtures/pending-prompts/${name}`, import.meta.url),
          "utf8",
        ),
      ),
    );
    const envelope = (text: string) =>
      JSON.stringify(
        agent === "codex"
          ? {
              timestamp: "2026-11-19T12:00:00Z",
              type: "response_item",
              payload: {
                type: "message",
                role: "user",
                content: [{ type: "input_text", text }],
              },
            }
          : {
              timestamp: "2026-11-19T12:00:00Z",
              type: "user",
              message: { role: "user", content: [{ type: "text", text }] },
            },
      );
    const records = screens.map(envelope);
    const size =
      Math.max(...records.map((text) => Buffer.byteLength(text))) + 1;
    const padded = records.map(
      (text) => text + "\n" + " ".repeat(size - Buffer.byteLength(text) - 1),
    );
    expect(Buffer.byteLength(padded[0]!)).toBe(Buffer.byteLength(padded[1]!));
    let text = padded[0]!;
    const file = {
      path: "/synthetic/recorded.jsonl",
      mtimeMs: 1000,
      size,
      identity: "same-inode",
      changeToken: "same-nanoseconds",
    };
    const files: AgentSessionFileAccess = {
      remote: false,
      statFile: async () => ({ ...file }),
      readText: async () => text,
      readPrefix: async (_path, limit) => Buffer.from(text).subarray(0, limit),
      readDownloadBody: async () => text,
      findPiSessionById: async () => null,
      findCodexSessionById: async () => null,
      findCodexSessionByPrefix: async () => null,
    };
    const resolved: AgentSessionResolved = {
      version: 1,
      agent,
      pane_id: "p1",
      workspace_id: "w1",
      tab_id: "tab1",
      status: "ok",
      detail: "",
      updated_at: "",
      path: file.path,
      session: {
        source: "recorded-vector",
        agent,
        kind: "path",
        value: file.path,
      },
      file,
    };
    const cache = createSessionProjectionCache(files);
    const first = await cache.history(resolved, undefined);
    expect(first.projection.messages.map((message) => message.text)).toContain(
      screens[0]!.trim(),
    );
    expect(
      (await cache.history(resolved, first.update.cursor)).update.cursor,
    ).toEqual(first.update.cursor);
    text = padded[1]!;
    const next = await cache.history(resolved, first.update.cursor);
    expect(next.projection.messages.map((message) => message.text)).toContain(
      screens[1]!.trim(),
    );
    expect(next.update.cursor).not.toEqual(first.update.cursor);
    expect(next.projection).not.toBe(first.projection);
  },
);
