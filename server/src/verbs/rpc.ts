const browser = policies({ browser: "allow" });
const rpc = (
  name: string,
  recovery: Recovery,
  capability: string,
  input = rpcInput(name),
) =>
  declare(
    "rpc",
    name,
    input,
    rpcOutput(name),
    recovery,
    browser,
    [capability],
    capability === "world"
      ? ["operation owner validation"]
      : ["current runtime lease", "operation owner validation"],
  );

