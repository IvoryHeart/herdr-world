import { readFileSync, readdirSync } from "node:fs";
import { basename, dirname, join } from "node:path";
import {
  GENERATED_MARKER,
  type ServicePaths,
  type ServicePlatform,
} from "./service-definitions";

export function isWorldServiceDefinition(contents: string): boolean {
  if (contents.includes(GENERATED_MARKER)) return true;
  // Some older packages retained the upstream marker. It is World's only
  // when the definition actually invokes the World executable, not herdr-gui.
  if (!contents.includes("Generated by herdr-gui service install."))
    return false;
  const argumentsXml =
    /<key>ProgramArguments<\/key>\s*<array>([\s\S]*?)<\/array>/.exec(
      contents,
    )?.[1] ?? "";
  return (
    /<string>[^<]*[/\\]herdr-world(?:\.exe)?<\/string>/.test(argumentsXml) ||
    /^ExecStart=[^\r\n]*[/\\]herdr-world(?:\.exe)?(?=[\s"]|$)/m.test(contents)
  );
}

/** Scan only user login definitions; never traverse core's state or system services. */
export function worldServiceDefinitions(
  platform: ServicePlatform,
  paths: ServicePaths,
): string[] {
  if (platform === "windows-task") return [paths.definition];
  const extension = platform === "launchd" ? ".plist" : ".service";
  const directory = dirname(paths.definition);
  let entries;
  try {
    entries = readdirSync(directory, { withFileTypes: true });
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT")
      return [paths.definition];
    throw error;
  }
  const definitions = [paths.definition];
  for (const entry of entries.sort((a, b) => a.name.localeCompare(b.name))) {
    if (!entry.isFile() || !entry.name.endsWith(extension)) continue;
    const path = join(directory, entry.name);
    if (path === paths.definition) continue;
    let contents;
    try {
      contents = readFileSync(path, "utf8");
    } catch {
      continue;
    }
    if (isWorldServiceDefinition(contents)) definitions.push(path);
  }
  return definitions;
}

/** A legacy plist's filename need not match the label launchd loaded. */
export function launchdServiceLabel(contents: string, path: string): string {
  const label = /<key>Label<\/key>\s*<string>([A-Za-z0-9._-]+)<\/string>/.exec(
    contents,
  )?.[1];
  if (label) return label;
  if (contents.includes("<key>Label</key>"))
    throw new Error(`invalid launchd Label in ${path}`);
  return basename(path, ".plist");
}
