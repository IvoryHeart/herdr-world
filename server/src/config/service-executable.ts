import { realpathSync } from "node:fs";
import { resolve } from "node:path";

/** Bun resolves the executable through Homebrew's symlinks before invoking us. */
export function stableServiceExecutable(execPath: string): string {
  const executable = resolve(execPath);
  const keg = /^(.*)\/Cellar\/(herdr-world(?:-rc)?)\/[^/]+\/(.+)$/.exec(
    executable,
  );
  if (!keg) return executable;
  const stable = `${keg[1]}/opt/${keg[2]}/${keg[3]}`;
  try {
    if (realpathSync(stable) === realpathSync(executable)) return stable;
  } catch {
    /* Refuse a missing or unrelated opt link before registering a service. */
  }
  throw new Error(
    "Homebrew opt link does not select this World; run brew link before service install",
  );
}

/** An upgrade may migrate only this formula's generated service, never another install. */
export function ownsHomebrewService(
  executable: string,
  definition: string,
): boolean {
  const keg = /^(.*)\/Cellar\/(herdr-world(?:-rc)?)\/[^/]+\/(.+)$/.exec(
    executable,
  );
  if (!keg) return false;
  const escape = (value: string) =>
    value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  const cellars = new RegExp(
    `${escape(keg[1]! + "/Cellar/" + keg[2]! + "/")}[^/<>\\s]+/${escape(keg[3]!)}`,
  );
  return (
    definition.includes("Generated by herdr-world service install.") &&
    (definition.includes(`${keg[1]}/opt/${keg[2]}/${keg[3]}`) ||
      cellars.test(definition))
  );
}
