import { afterEach, describe, expect, test } from "bun:test";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { EXIT_FAILURE, EXIT_OK, EXIT_USAGE } from "./command";
import { ConnectionProfileStore } from "../connections/profiles";
import { acquireInstanceLock } from "../config/instance-lock";
import {
  type ConnectionsDependencies,
  createConnectionsCommand,
} from "./connections";
import { runCli } from "./index";
import { createTestCli, type TestCli } from "./test-context";

let cli: TestCli;
afterEach(() => cli?.cleanup());

const idle: ConnectionsDependencies = {
  probe: async () => false,
  herdrInstalled: async () => true,
};

function registry(testCli: TestCli) {
  return JSON.parse(
    readFileSync(
      join(testCli.home, ".config", "herdr-world", "connections.json"),
      "utf8",
    ),
  );
}

async function connections(args: string[], dependencies = idle) {
  return runCli(["connections", ...args], cli.context, [
    createConnectionsCommand(dependencies),
  ]);
}

function managedService(config = "") {
  cli = createTestCli({
    runCommand: (argv) => {
      if (argv.includes("restart"))
        expect(
          registry(cli).profiles.some((p: { id: string }) => p.id === "box"),
        ).toBe(true);
      return argv.includes("herdr-gui.service") ? 4 : 0;
    },
  });
  cli.writeConfig(config);
  const units = join(cli.home, ".config", "systemd", "user");
  mkdirSync(units, { recursive: true });
  writeFileSync(
    join(units, "herdr-world.service"),
    "# Generated by herdr-world service install.\n",
  );
}

describe("herdr-world connections", () => {
  test("lists the implicit default from the service config", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    expect(await connections(["list", "--json"])).toBe(EXIT_OK);
    const listed = JSON.parse(cli.output.join("\n"));
    expect(listed.default_connection_id).toBe("startup-default");
    expect(listed.profiles[0]).toMatchObject({
      saved: false,
      control_socket_path: join(cli.home, ".config", "herdr", "herdr.sock"),
    });
  });

  test("the first saved profile keeps the local server, like the web UI", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    expect(
      await connections([
        "add",
        "box",
        "--ssh",
        "me@box",
        "--label",
        "Box",
        "--auto-connect",
      ]),
    ).toBe(EXIT_OK);
    const saved = registry(cli);
    expect(saved.default_connection_id).toBe("local");
    expect(saved.profiles.map((profile: { id: string }) => profile.id)).toEqual(
      ["local", "box"],
    );
    expect(saved.profiles[1]).toEqual({
      id: "box",
      label: "Box",
      type: "ssh",
      ssh_destination: "me@box",
      remote_control_socket_path: "",
      remote_client_socket_path: "",
      auto_connect: true,
    });
  });

  test("a new profile named local seeds localhost instead", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    await connections(["add", "local", "--ssh", "me@box", "--default"]);
    const saved = registry(cli);
    expect(saved.profiles[0].id).toBe("localhost");
    expect(saved.default_connection_id).toBe("local");
  });

  test("--core saves a herdr-core connection; the default stays Herdr", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    expect(
      await connections([
        "add",
        "core-local",
        "--core",
        "--auto-connect",
        "--label",
        "herdr-core on this computer",
      ]),
    ).toBe(EXIT_OK);
    expect(
      await connections([
        "add",
        "core-dev",
        "--core",
        "--ssh",
        "dev.example.com",
        "--session",
        "work",
      ]),
    ).toBe(EXIT_OK);
    const saved = registry(cli);
    expect(saved.default_connection_id).toBe("local");
    expect(saved.profiles.slice(1)).toEqual([
      {
        id: "core-local",
        label: "herdr-core on this computer",
        type: "local",
        runtime: "herdr-core",
        core_session: "default",
        core_state_dir: "",
        auto_connect: true,
      },
      {
        id: "core-dev",
        label: "core-dev",
        type: "ssh",
        runtime: "herdr-core",
        ssh_destination: "dev.example.com",
        core_session: "work",
        core_state_dir: "",
        auto_connect: false,
      },
    ]);
    for (const extra of [["--windows"], ["--herdr-path", "/x"]])
      expect(await connections(["add", "c", "--core", ...extra])).toBe(
        EXIT_USAGE,
      );
  });

  test("the installers' core registration on a computer without the Herdr TUI saves core alone, as the default", async () => {
    // The exact arguments the standalone installer and Homebrew run (#935).
    const bootstrap = readFileSync(
      join(import.meta.dir, "../../../scripts/homebrew-herdr-bootstrap.sh"),
      "utf8",
    );
    const line = bootstrap.match(
      /"\$world" connections add (core-local [^>]*?) >\/dev\/null/,
    )?.[1];
    expect(line).toBeDefined();
    const args = line!
      .match(/'[^']*'|\S+/g)!
      .map((word) => word.replace(/^'|'$/g, ""));
    for (const installed of [false, true]) {
      cli = createTestCli();
      cli.writeConfig("");
      const asked: string[] = [];
      expect(
        await connections(["add", ...args], {
          ...idle,
          herdrInstalled: async (implicit) => {
            asked.push(implicit.control_socket_path);
            return installed;
          },
        }),
      ).toBe(EXIT_OK);
      expect(asked).toEqual([join(cli.home, ".config", "herdr", "herdr.sock")]);
      const saved = registry(cli);
      expect(saved.default_connection_id).toBe("core-local");
      // A Herdr TUI, should one be present after all, stays listed.
      expect(
        saved.profiles.map((profile: { id: string }) => profile.id),
      ).toEqual(installed ? ["local", "core-local"] : ["core-local"]);
      cli.cleanup();
    }
    // Without --default and without the Herdr TUI, core is still the default:
    // there is no Herdr connection to be one.
    cli = createTestCli();
    cli.writeConfig("");
    expect(
      await connections(["add", "core-local", "--core"], {
        ...idle,
        herdrInstalled: async () => false,
      }),
    ).toBe(EXIT_OK);
    expect(registry(cli)).toMatchObject({
      default_connection_id: "core-local",
      profiles: [{ id: "core-local", runtime: "herdr-core" }],
    });
  });

  test("concurrent offline first saves retain both successful additions", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    // Both old snapshots would see no registry while the first detection yields.
    const dependencies = { ...idle, herdrInstalled: async () => true };
    const receipts = await Promise.all([
      connections(["add", "beta", "--core"], dependencies),
      connections(["add", "gamma", "--core"], dependencies),
    ]);
    expect(receipts).toEqual([EXIT_OK, EXIT_OK]);
    expect(
      registry(cli)
        .profiles.map((p: { id: string }) => p.id)
        .sort(),
    ).toEqual(["beta", "gamma", "local"]);
  });

  test("all 24 admission orders retain unrelated additions, removal and default changes", async () => {
    const operations = [
      ["add", "beta", "--core"],
      ["add", "gamma", "--core"],
      ["set-default", "delta"],
      ["remove", "omega"],
    ];
    function permutations(items: string[][]): string[][][] {
      return items.length === 0
        ? [[]]
        : items.flatMap((item, i) =>
            permutations(items.filter((_, j) => j !== i)).map((rest) => [
              item,
              ...rest,
            ]),
          );
    }
    const orders = permutations(operations);
    expect(orders).toHaveLength(24);
    for (const order of orders) {
      cli = createTestCli();
      cli.writeConfig("");
      const path = join(cli.home, ".config", "herdr-world", "connections.json");
      const store = new ConnectionProfileStore({ path });
      await store.save({
        version: 2,
        default_connection_id: "alpha",
        profiles: ["alpha", "delta", "omega"].map((id) => ({
          id,
          label: id,
          type: "local",
          runtime: "herdr-core",
          core_session: "default",
          core_state_dir: "",
          auto_connect: false,
        })),
      });
      expect(await Promise.all(order.map((args) => connections(args)))).toEqual(
        [0, 0, 0, 0],
      );
      const reopened = new ConnectionProfileStore({ path }).load()!;
      expect(reopened.profiles.map((p) => p.id).sort()).toEqual([
        "alpha",
        "beta",
        "delta",
        "gamma",
      ]);
      expect(reopened.default_connection_id).toBe("delta");
      cli.cleanup();
    }
  });

  test("a failed offline edit releases ownership for the next addition", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    await connections(["add", "beta", "--core"]);
    expect(
      await Promise.all([
        connections(["add", "beta", "--core"]),
        connections(["add", "gamma", "--core"]),
      ]),
    ).toEqual([EXIT_USAGE, EXIT_OK]);
    expect(
      registry(cli)
        .profiles.map((p: { id: string }) => p.id)
        .sort(),
    ).toEqual(["beta", "gamma", "local"]);
  });

  test("startup between the initial probe and offline snapshot refuses the edit", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    const probed = Promise.withResolvers<void>();
    const proceed = Promise.withResolvers<boolean>();
    const editing = connections(["add", "beta", "--core"], {
      ...idle,
      probe: () => {
        probed.resolve();
        return proceed.promise;
      },
    });
    await probed.promise;
    const release = acquireInstanceLock(
      join(cli.home, ".config", "herdr-world"),
      0,
    );
    try {
      proceed.resolve(false);
      expect(await editing).toBe(EXIT_FAILURE);
      expect(cli.errors.join()).toContain(
        "has not recorded a listening address",
      );
      expect(
        existsSync(
          join(cli.home, ".config", "herdr-world", "connections.json"),
        ),
      ).toBe(false);
    } finally {
      release();
    }
  });

  test("enforces the same removal and default rules as the server", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    await connections(["add", "box", "--ssh", "me@box"]);
    expect(await connections(["remove", "local"])).toBe(EXIT_USAGE);
    expect(cli.errors.at(-2)).toContain("cannot remove the default connection");
    expect(await connections(["set-default", "box"])).toBe(EXIT_OK);
    expect(await connections(["remove", "local"])).toBe(EXIT_OK);
    // The last saved profile is always the default, as on the server.
    expect(await connections(["remove", "box"])).toBe(EXIT_USAGE);
    expect(cli.errors.at(-2)).toContain("cannot remove the default connection");
    expect(await connections(["add", "box", "--ssh", "me@other"])).toBe(
      EXIT_USAGE,
    );
    expect(cli.errors.at(-2)).toContain("already exists");
  });

  test("rejects invalid profiles as usage errors", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    expect(await connections(["add", "x"])).toBe(EXIT_USAGE);
    expect(
      await connections(["add", "x", "--windows", "--control-socket", "/a"]),
    ).toBe(EXIT_USAGE);
    expect(
      await connections(["add", "x", "--ssh", "-oProxyCommand=evil"]),
    ).toBe(EXIT_USAGE);
    expect(
      existsSync(join(cli.home, ".config", "herdr-world", "connections.json")),
    ).toBe(false);
  });

  test("does not fall back to an offline write when live admission fails", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    const serving: ConnectionsDependencies = {
      probe: async () => true,
      apply: async () => {
        throw new Error("live service unavailable");
      },
    };
    expect(await connections(["add", "box", "--ssh", "me@box"], serving)).toBe(
      EXIT_FAILURE,
    );
    expect(cli.errors[0]).toContain("No offline write was attempted");
    expect(
      existsSync(join(cli.home, ".config", "herdr-world", "connections.json")),
    ).toBe(false);
  });

  test("restarts a running managed service with --restart", async () => {
    cli = createTestCli({
      runCommand: (argv) => (argv.includes("herdr-gui.service") ? 4 : 0),
    });
    cli.writeConfig("");
    mkdirSync(join(cli.home, ".config", "systemd", "user"), {
      recursive: true,
    });
    writeFileSync(
      join(cli.home, ".config", "systemd", "user", "herdr-world.service"),
      "# Generated by herdr-world service install.\n",
    );
    const admitted: string[] = [];
    const serving: ConnectionsDependencies = {
      probe: async () => true,
      apply: async (_context, _setup, action) => {
        admitted.push(action);
        expect(cli.commands.some((args) => args.includes("restart"))).toBe(
          false,
        );
        return { ok: true };
      },
    };
    expect(
      await connections(
        ["add", "box", "--ssh", "me@box", "--restart"],
        serving,
      ),
    ).toBe(EXIT_OK);
    expect(admitted).toEqual(["add"]);
    expect(
      existsSync(join(cli.home, ".config", "herdr-world", "connections.json")),
    ).toBe(false);
    expect(cli.commands).toContainEqual([
      "systemctl",
      "--user",
      "restart",
      "herdr-world.service",
    ]);
  });

  test("test reports each profile and fails when any is unreachable", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    await connections(["add", "box", "--ssh", "me@box"]);
    cli.output.length = 0;
    const code = await connections(["test", "--json"], {
      ...idle,
      test: async (profile) => {
        if (profile.type === "ssh") throw new Error("ssh: connection refused");
        return { ok: true, version: "0.9.4", protocol: 7 };
      },
    });
    expect(code).toBe(EXIT_FAILURE);
    expect(JSON.parse(cli.output.join("\n")).results).toEqual([
      { id: "local", ok: true, version: "0.9.4", protocol: 7 },
      { id: "box", ok: false, error: "ssh: connection refused" },
    ]);
    expect(await connections(["test", "nope"])).toBe(EXIT_USAGE);
  });

  test.each([false, true])(
    "an active but unreachable managed service retains offline edits (restart: %s)",
    async (restart) => {
      managedService();
      expect(
        await connections([
          "add",
          "box",
          "--ssh",
          "box.example.com",
          ...(restart ? ["--restart"] : []),
        ]),
      ).toBe(EXIT_OK);
      expect(
        registry(cli).profiles.some((p: { id: string }) => p.id === "box"),
      ).toBe(true);
      // Before live admission, an unanswered probe saved only, even with --restart.
      expect(cli.commands.some((args) => args.includes("restart"))).toBe(false);
    },
  );

  test("--restart saves before restarting a managed service bound to one non-loopback address", async () => {
    managedService("HOST=192.0.2.10\n");
    const serving: ConnectionsDependencies = {
      ...idle,
      probe: async () => cli.commands.at(-1)?.includes("stop") !== true,
      apply: async () => {
        throw new Error("non-loopback listeners cannot admit live edits");
      },
    };
    expect(
      await connections(
        ["add", "box", "--ssh", "box.example.com", "--restart"],
        serving,
      ),
    ).toBe(EXIT_OK);
    expect(cli.commands).toContainEqual([
      "systemctl",
      "--user",
      "stop",
      "herdr-world.service",
    ]);
    expect(cli.commands).toContainEqual([
      "systemctl",
      "--user",
      "start",
      "herdr-world.service",
    ]);
    expect(
      await connections(["set-default", "box", "--restart"], serving),
    ).toBe(EXIT_OK);
    expect(registry(cli).default_connection_id).toBe("box");
    expect(await connections(["remove", "local", "--restart"], serving)).toBe(
      EXIT_OK,
    );
    expect(registry(cli).profiles.map((p: { id: string }) => p.id)).toEqual([
      "box",
    ]);
  });

  test("non-loopback restart starts the stopped service after an edit refusal", async () => {
    managedService("HOST=192.0.2.10\n");
    const serving = {
      ...idle,
      probe: async () => cli.commands.at(-1)?.includes("stop") !== true,
    };
    expect(await connections(["remove", "absent", "--restart"], serving)).toBe(
      EXIT_USAGE,
    );
    expect(cli.commands).toContainEqual([
      "systemctl",
      "--user",
      "stop",
      "herdr-world.service",
    ]);
    expect(cli.commands.at(-1)).toEqual([
      "systemctl",
      "--user",
      "start",
      "herdr-world.service",
    ]);
    expect(
      existsSync(join(cli.home, ".config", "herdr-world", "connections.json")),
    ).toBe(false);
  });

  test.each([false, true])(
    "a non-loopback foreground listener never permits an offline write (restart: %s)",
    async (restart) => {
      cli = createTestCli();
      cli.writeConfig("HOST=192.0.2.10\n");
      await connections(["add", "box", "--ssh", "box.example.com"]);
      const before = registry(cli);
      const serving = { ...idle, probe: async () => true };
      for (const args of [
        ["add", "other", "--ssh", "other.example.com"],
        ["set-default", "box"],
        ["remove", "box"],
      ]) {
        expect(
          await connections(
            [...args, ...(restart ? ["--restart"] : [])],
            serving,
          ),
        ).toBe(EXIT_FAILURE);
        expect(registry(cli)).toEqual(before);
      }
      expect(cli.commands.some((args) => args.includes("restart"))).toBe(false);
    },
  );

  test("a non-loopback managed listener still requires --restart for an offline write", async () => {
    managedService("HOST=192.0.2.10\n");
    expect(
      await connections(["add", "box", "--ssh", "box.example.com"], {
        ...idle,
        probe: async () => true,
      }),
    ).toBe(EXIT_FAILURE);
    expect(
      existsSync(join(cli.home, ".config", "herdr-world", "connections.json")),
    ).toBe(false);
  });

  test("help explains live edits and optional restarts", async () => {
    cli = createTestCli();
    expect(await connections(["--help"])).toBe(EXIT_OK);
    expect(cli.output.join("\n")).toContain("admits these changes live");
    expect(cli.output.join("\n")).toContain("no longer needed");
    expect(cli.output.join("\n")).toContain("HERDR_WORLD_DATA_DIR");
    expect(cli.output.join("\n")).toContain("instance lock");
    expect(cli.output.join("\n")).toContain("cannot redirect connection edits");
    expect(cli.output.join("\n")).toMatch(
      /--auto-connect\s+connect at startup and at once on a running World/,
    );
  });

  test("explicit Herdr settings stay out of a saved registry", async () => {
    cli = createTestCli();
    cli.writeConfig("");
    await connections(["add", "box", "--ssh", "me@box"]);
    cli.writeConfig("HERDR_SESSION=work\n");
    expect(await connections(["add", "lab", "--ssh", "me@lab"])).toBe(EXIT_OK);
    expect(await connections(["remove", "box"])).toBe(EXIT_OK);
    const saved = registry(cli);
    expect(saved.profiles.map((profile: { id: string }) => profile.id)).toEqual(
      ["local", "lab"],
    );
    cli.output.length = 0;
    await connections(["list", "--json"]);
    const listed = JSON.parse(cli.output.join("\n"));
    expect(listed.default_connection_id).toBe("startup-default");
    expect(listed.profiles[0]).toMatchObject({
      id: "startup-default",
      saved: false,
      control_socket_path: join(
        cli.home,
        ".config",
        "herdr",
        "sessions",
        "work",
        "herdr.sock",
      ),
    });
  });
});
